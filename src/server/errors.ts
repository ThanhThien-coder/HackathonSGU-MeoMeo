const RETRYABLE_CODES = new Set<ErrorCode>([
  "ERR_NETWORK_TIMEOUT",
  "ERR_STREAM_TIMEOUT",
  "ERR_GITHUB_RATE_LIMIT_CDN",
  "ERR_SERVER_BUSY",
  "ERR_AI_UNAVAILABLE",
  "ERR_PERSISTENCE_UNAVAILABLE",
  "ERR_ATTEMPT_OUT_OF_SYNC",
]);

export function isRetryable(code: ErrorCode): boolean {
  return RETRYABLE_CODES.has(code);
}
